"""
ComfyUI API Client.
Encapsulates HTTP communication with the official ComfyUI server endpoints:
workflow submission (/prompt), queue inspection (/queue), history lookup (/history),
and artifact retrieval (/view).
"""

import uuid
import logging
import requests
from typing import Dict, Any, Optional

from server.services.comfyui.config import ComfyUIConfig
from server.services.comfyui.exceptions import (
    ComfyUINetworkError,
    ComfyUIExecutionError
)

logger = logging.getLogger("ComfyUI.APIClient")


class ComfyUIClient:
    """Official ComfyUI REST API client."""

    def __init__(self, config: Optional[ComfyUIConfig] = None):
        self.config = config or ComfyUIConfig.from_env()
        self.base_url = self.config.api_url.rstrip("/")
        self.client_id = str(uuid.uuid4())
        self.session = requests.Session()

    def _get_headers(self) -> Dict[str, str]:
        """Construct HTTP headers with optional authorization token."""
        headers = {
            "Content-Type": "application/json",
            "User-Agent": "StyleAI-ComfyUI-Client/1.0"
        }
        if self.config.api_key:
            headers["Authorization"] = f"Bearer {self.config.api_key}"
            headers["X-API-Key"] = self.config.api_key
        return headers

    def check_health(self) -> bool:
        """Verify ComfyUI server accessibility."""
        try:
            url = f"{self.base_url}/system_stats"
            res = self.session.get(url, headers=self._get_headers(), timeout=5.0)
            return res.status_code == 200
        except Exception:
            return False

    def submit_prompt(self, workflow: Dict[str, Any]) -> str:
        """
        Submit a workflow prompt to ComfyUI for execution.

        Args:
            workflow: ComfyUI node dictionary.

        Returns:
            prompt_id (str): Unique job identifier generated by ComfyUI.

        Raises:
            ComfyUINetworkError: If API request fails or server is unreachable.
            ComfyUIExecutionError: If ComfyUI rejects the workflow with validation errors.
        """
        url = f"{self.base_url}/prompt"
        payload = {
            "prompt": workflow,
            "client_id": self.client_id
        }

        logger.info(f"Submitting workflow to ComfyUI at {url} (client_id={self.client_id})")

        try:
            response = self.session.post(
                url,
                json=payload,
                headers=self._get_headers(),
                timeout=15.0
            )
        except requests.exceptions.RequestException as err:
            logger.error(f"Network failure connecting to ComfyUI at {url}: {err}")
            raise ComfyUINetworkError(
                f"Failed to connect to ComfyUI server at '{url}': {err}"
            ) from err

        if response.status_code != 200:
            err_text = response.text[:500]
            logger.error(f"ComfyUI submission failed [HTTP {response.status_code}]: {err_text}")
            raise ComfyUIExecutionError(
                f"ComfyUI rejected prompt [HTTP {response.status_code}]: {err_text}"
            )

        try:
            res_data = response.json()
        except Exception as err:
            raise ComfyUINetworkError(
                f"Invalid JSON response received from ComfyUI: {response.text[:200]}"
            ) from err

        # Check for node validation errors returned by ComfyUI
        if "node_errors" in res_data and res_data["node_errors"]:
            node_errs = res_data["node_errors"]
            logger.error(f"ComfyUI node validation errors: {node_errs}")
            raise ComfyUIExecutionError(f"ComfyUI node validation error: {node_errs}")

        prompt_id = res_data.get("prompt_id")
        if not prompt_id:
            raise ComfyUIExecutionError(
                f"ComfyUI response did not return a prompt_id: {res_data}"
            )

        logger.info(f"Workflow submitted successfully. Job prompt_id: {prompt_id}")
        return str(prompt_id)

    def get_history(self, prompt_id: str) -> Dict[str, Any]:
        """
        Query execution history and output metadata for a given prompt_id.

        Args:
            prompt_id: The job ID returned from submit_prompt.

        Returns:
            Dict representing the history response from /history/{prompt_id}.
        """
        url = f"{self.base_url}/history/{prompt_id}"
        try:
            response = self.session.get(
                url,
                headers=self._get_headers(),
                timeout=10.0
            )
        except requests.exceptions.RequestException as err:
            raise ComfyUINetworkError(
                f"Failed to fetch history for prompt_id '{prompt_id}': {err}"
            ) from err

        if response.status_code != 200:
            raise ComfyUINetworkError(
                f"History request failed [HTTP {response.status_code}]: {response.text[:200]}"
            )

        return response.json()

    def get_queue(self) -> Dict[str, Any]:
        """Query queue status (/queue)."""
        url = f"{self.base_url}/queue"
        try:
            response = self.session.get(
                url,
                headers=self._get_headers(),
                timeout=10.0
            )
            return response.json()
        except Exception as err:
            logger.warning(f"Could not retrieve queue status: {err}")
            return {}

    def fetch_image_bytes(self, filename: str, subfolder: str = "", folder_type: str = "output") -> bytes:
        """
        Download rendered image binary data from ComfyUI /view endpoint.

        Args:
            filename: Name of generated image file.
            subfolder: Subfolder within ComfyUI output directory.
            folder_type: Storage bucket type ('output', 'input', 'temp').

        Returns:
            bytes: Raw image binary data.
        """
        url = f"{self.base_url}/view"
        params = {
            "filename": filename,
            "subfolder": subfolder,
            "type": folder_type
        }

        logger.info(f"Downloading generated image from ComfyUI: {filename} (type={folder_type})")

        try:
            response = self.session.get(
                url,
                params=params,
                headers=self._get_headers(),
                timeout=30.0
            )
        except requests.exceptions.RequestException as err:
            raise ComfyUINetworkError(
                f"Failed to download image '{filename}' from ComfyUI: {err}"
            ) from err

        if response.status_code != 200:
            raise ComfyUINetworkError(
                f"Failed to fetch image '{filename}' [HTTP {response.status_code}]"
            )

        data = response.content
        if not data:
            raise ComfyUINetworkError(f"Downloaded image '{filename}' was empty (0 bytes).")

        logger.info(f"Successfully downloaded image '{filename}' ({len(data)} bytes).")
        return data
